using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Fastcull.Benchmarks
{
    /// <summary>
    /// Emits the results file PRD 3.5's "regression greater than 25% fails the build" rule will
    /// eventually be checked against. Deliberately writes the NOT MEASURABLE rows alongside the
    /// measured ones: a budget table that silently omits the four metrics whose features do not
    /// exist reads as though the app passes everything, which is the opposite of true.
    /// </summary>
    internal static class MarkdownReport
    {
        private static string Plain(string metric) => metric.Replace("**", string.Empty);

        /// <summary>
        /// Read back from the run rather than written into the prose. The corpus grows as sample
        /// files are added, and a hardcoded count silently becomes a lie in the file that exists
        /// specifically to be trusted about its own methodology.
        /// </summary>
        private static string RealCorpusFiles(HarnessResults results)
            => results.Environment.TryGetValue("Real corpus files", out var count) ? count : "the real corpus's";

        public static string Render(HarnessResults results, string generatedAtUtc, string title)
        {
            var sb = new StringBuilder();

            sb.AppendLine($"# {title}");
            sb.AppendLine();
            sb.AppendLine("Generated by `dotnet run -c Release --project Fastcull.Benchmarks`.");
            sb.AppendLine($"Run at {generatedAtUtc} UTC.");
            sb.AppendLine();
            sb.AppendLine("This is the reference point for PRD 3.5's \"a regression greater than 25% fails the");
            sb.AppendLine("build\" rule. Wiring that into an actual CI gate is future work — this file is the");
            sb.AppendLine("baseline it would compare against, not the gate itself.");
            sb.AppendLine();

            sb.AppendLine("## Environment");
            sb.AppendLine();
            sb.AppendLine("| | |");
            sb.AppendLine("| :--- | :--- |");
            foreach (var kv in results.Environment)
                sb.AppendLine($"| {kv.Key} | {kv.Value} |");
            sb.AppendLine();

            var measured = results.Budgets.Where(b => b.Unmeasurable == Unmeasurable.No).ToList();
            var notMeasurable = results.Budgets.Where(b => b.Unmeasurable != Unmeasurable.No).ToList();

            sb.AppendLine("## Measured");
            sb.AppendLine();
            sb.AppendLine("| Metric | PRD budget | Measured | Status |");
            sb.AppendLine("| :--- | :--- | ---: | :--- |");
            foreach (var b in measured)
                sb.AppendLine($"| {b.Metric} | {b.Budget} | {b.MeasuredText} | {b.StatusText} |");

            foreach (var m in results.Memory)
            {
                var value = string.Create(CultureInfo.InvariantCulture,
                    $"{(m.MeasuredMb >= 1024 ? m.MeasuredMb / 1024 : m.MeasuredMb):F2} {(m.MeasuredMb >= 1024 ? "GB" : "MB")}");
                sb.AppendLine($"| {m.Metric} | {m.Budget} | {value} | {m.StatusText} |");
            }
            sb.AppendLine();

            if (results.Memory.Any(m => m.Informational))
            {
                sb.AppendLine("**`REFERENCE` rows are measured and compared against their budget, but do not gate the");
                sb.AppendLine("build.** They benchmark the eager-fan-out architecture PRD 3.3 replaced. They are kept —");
                sb.AppendLine("rather than deleted, or silently excluded — because running them in the *same* run as the");
                sb.AppendLine("shipping path is what proves the improvement is architectural rather than day-to-day");
                sb.AppendLine("variance between two runs. A row measuring code that no longer ships must never be able");
                sb.AppendLine("to fail the build on its own, so `REFERENCE (over budget)` is a fact about the old design,");
                sb.AppendLine("not a regression in the current one.");
                sb.AppendLine();
            }

            sb.AppendLine("### Detail");
            sb.AppendLine();
            // Metric names may already carry emphasis for the table; strip it so the bullet's own
            // bold does not nest into "****" and render as literal asterisks.
            foreach (var b in measured.Where(x => !string.IsNullOrWhiteSpace(x.Detail)))
                sb.AppendLine($"- **{Plain(b.Metric)}** — {b.Detail}");
            foreach (var m in results.Memory.Where(x => !string.IsNullOrWhiteSpace(x.Detail)))
                sb.AppendLine($"- **{Plain(m.Metric)}** — {m.Detail}");
            sb.AppendLine();

            sb.AppendLine("## Not measurable yet");
            sb.AppendLine();
            sb.AppendLine("These are PRD 3.5 budgets with no number, because the feature they measure does not");
            sb.AppendLine("exist. None of them was approximated by timing something adjacent.");
            sb.AppendLine();
            sb.AppendLine("| Metric | PRD budget | Why there is no number |");
            sb.AppendLine("| :--- | :--- | :--- |");
            foreach (var b in notMeasurable)
                sb.AppendLine($"| {b.Metric} | {b.Budget} | {b.Reason} |");
            sb.AppendLine();

            if (results.Notes.Count > 0)
            {
                sb.AppendLine("## Corpus");
                sb.AppendLine();
                foreach (var note in results.Notes)
                    sb.AppendLine($"- {note}");
                sb.AppendLine();
            }

            sb.AppendLine("## How to read this");
            sb.AppendLine();
            sb.AppendLine($"- **Real vs. synthetic file counts.** The real corpus is {RealCorpusFiles(results)} files. The two budgets");
            sb.AppendLine("  PRD 3.5 defines at \"2,000 files\" are measured against a synthetic corpus of 2,000");
            sb.AppendLine($"  NTFS hard links cycling over those {RealCorpusFiles(results)} files — **2,000 real photos were not used**.");
            sb.AppendLine("  Hard links are genuine directory entries over the real bytes, so enumeration,");
            sb.AppendLine($"  `FileInfo.Length` and header parsing all do real work, but 2,000 entries share {RealCorpusFiles(results)}");
            sb.AppendLine("  extents, so the OS page cache is warmer than it would be for 2,000 distinct files.");
            sb.AppendLine("  That biases scan and decode timings **optimistically**. The \"real corpus (control)\"");
            sb.AppendLine("  row exists to bound that bias: compare its ms/file against the synthetic one.");
            sb.AppendLine("- **Every timing here is warm-cache.** The harness scans the corpus once to build");
            sb.AppendLine("  its fixture sets before it measures anything, so the OS page cache is already hot");
            sb.AppendLine("  by the time the scan is timed. A genuinely cold first-open of a 2,000-file folder");
            sb.AppendLine("  off NVMe is **not** measured by this run and will be slower — possibly much");
            sb.AppendLine("  slower. Read the scan and first-image rows as a floor, not as the number a user");
            sb.AppendLine("  sees when they open a card for the first time.");
            sb.AppendLine("- **\"First image\" is a proxy.** It measures folder-open to the first decoded");
            sb.AppendLine("  thumbnail — pixels in hand, not pixels lit. It stops before the XAML");
            sb.AppendLine("  `SoftwareBitmapSource` marshal, previously measured at roughly 30 ms, negligible");
            sb.AppendLine("  against a 1.5 s budget.");
            sb.AppendLine("- **The rating row is decision latency**, not end-to-end. `PropertyChanged` is raised");
            sb.AppendLine("  in `FilmstripItemViewModel`, which lives in the WinUI project and cannot be");
            sb.AppendLine("  constructed headlessly; the compositor repaint after it is GPU-scheduled and not");
            sb.AppendLine("  the app's to time.");
            sb.AppendLine("- **The peak-working-set rows measure two different architectures, on purpose.** The");
            sb.AppendLine("  `REFERENCE` rows reproduce the pre-PRD-3.3 code: every constructed item started both");
            sb.AppendLine("  decodes immediately and nothing ever released one. The \"window + LRU eviction\" row");
            sb.AppendLine("  reproduces what ships now and is the one that gates. The first is kept deliberately —");
            sb.AppendLine("  it is the number the second has to beat, and deleting it would hide the comparison.");
            sb.AppendLine("- **The memory rows hold `SoftwareBitmap`, the app holds `SoftwareBitmapSource`.** A");
            sb.AppendLine("  `SoftwareBitmapSource` additionally copies pixels into a XAML composition surface,");
            sb.AppendLine("  which may live in GPU memory and is not this process's working set to sample. Read");
            sb.AppendLine("  every peak here as **system RAM only** — the PRD 3.5 budget's own unit — and note that");
            sb.AppendLine("  PRD 3.3's VRAM ceiling is separate, v0.4 scope, and unbuilt.");
            sb.AppendLine("- **Eviction disposes nothing.** Both the app and this harness drop the last managed");
            sb.AppendLine("  reference and let the GC reclaim, because disposing a bitmap XAML may still be copying");
            sb.AppendLine("  fail-fasts the process with `0xC000027B`. Peak working set therefore depends on when");
            sb.AppendLine("  the GC runs, not only on when the app lets go. That is real app behaviour, not a");
            sb.AppendLine("  harness artefact.");
            sb.AppendLine("- **The cache-hit row counts only genuine hits.** A step where the incoming photo still");
            sb.AppendLine("  had to be decoded is recorded as a miss and excluded from the timing, so the number");
            sb.AppendLine("  cannot be a decode wearing a cache-hit label. Its hit rate is in the row's detail.");
            sb.AppendLine("- **No BenchmarkDotNet.** PRD 3.5 wants a regression gate that runs routinely, not a");
            sb.AppendLine("  statistically rigorous micro-benchmark suite with warm-up iterations taking minutes");
            sb.AppendLine("  per run. A `Stopwatch` harness running the real pipeline against the PRD's absolute");
            sb.AppendLine("  budgets fits PRD 5's architecture (`Benchmarks/PerfHarness.cs`) and this project's");
            sb.AppendLine("  no-new-packages default. The tradeoff is real and worth naming: single-run timings");
            sb.AppendLine("  are noisier than a proper harness would produce, so treat a change under about 25%");
            sb.AppendLine("  as noise — which is, conveniently, exactly the threshold PRD 3.5 sets.");

            return sb.ToString();
        }
    }
}
